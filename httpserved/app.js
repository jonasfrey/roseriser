// Factory function to create SVG viewer for a panel
function createSvgViewer(containerId, wrapperId, headerId) {
    return {
        scale: 1,
        translateX: 0,
        translateY: 0,
        isDragging: false,
        lastX: 0,
        lastY: 0,
        containerId,
        wrapperId,
        headerId,

        init() {
            const container = document.getElementById(this.containerId);
            if (!container) return;

            container.addEventListener('wheel', (e) => {
                e.preventDefault();
                const delta = e.deltaY > 0 ? 0.9 : 1.1;
                const rect = container.getBoundingClientRect();
                const x = e.clientX - rect.left;
                const y = e.clientY - rect.top;

                const newScale = Math.max(0.1, Math.min(10, this.scale * delta));
                const scaleChange = newScale / this.scale;

                this.translateX = x - (x - this.translateX) * scaleChange;
                this.translateY = y - (y - this.translateY) * scaleChange;
                this.scale = newScale;
                this.updateTransform();
            });

            container.addEventListener('mousedown', (e) => {
                this.isDragging = true;
                this.lastX = e.clientX;
                this.lastY = e.clientY;
            });

            container.addEventListener('mousemove', (e) => {
                if (!this.isDragging) return;
                this.translateX += e.clientX - this.lastX;
                this.translateY += e.clientY - this.lastY;
                this.lastX = e.clientX;
                this.lastY = e.clientY;
                this.updateTransform();
            });

            container.addEventListener('mouseup', () => { this.isDragging = false; });
            container.addEventListener('mouseleave', () => { this.isDragging = false; });
        },

        updateTransform() {
            const wrapper = document.getElementById(this.wrapperId);
            if (wrapper) {
                wrapper.style.transform = `translate(${this.translateX}px, ${this.translateY}px) scale(${this.scale})`;
            }
        },

        fitToContainer() {
            const container = document.getElementById(this.containerId);
            const wrapper = document.getElementById(this.wrapperId);
            if (!container || !wrapper) return;
            const svg = wrapper.querySelector('svg');
            if (!svg) return;

            // Reset first
            this.scale = 1;
            this.translateX = 0;
            this.translateY = 0;
            this.updateTransform();

            // Calculate fit
            setTimeout(() => {
                const containerRect = container.getBoundingClientRect();
                const svgRect = svg.getBoundingClientRect();
                if (svgRect.width === 0 || svgRect.height === 0) return;

                const scaleX = (containerRect.width - 20) / svgRect.width;
                const scaleY = (containerRect.height - 20) / svgRect.height;
                this.scale = Math.min(scaleX, scaleY, 2);

                this.translateX = (containerRect.width - svgRect.width * this.scale) / 2;
                this.translateY = (containerRect.height - svgRect.height * this.scale) / 2;
                this.updateTransform();
            }, 50);
        },

        reset() {
            this.scale = 1;
            this.translateX = 0;
            this.translateY = 0;
            this.updateTransform();
        },

        setSVG(svgString) {
            const wrapper = document.getElementById(this.wrapperId);
            const header = document.getElementById(this.headerId);
            if (!wrapper) return;

            wrapper.innerHTML = svgString;
            const svg = wrapper.querySelector('svg');
            if (svg) {
                svg.style.width = 'auto';
                svg.style.height = 'auto';
                svg.style.maxWidth = '100%';
                svg.style.maxHeight = '100%';
            }
            if (header) {
                header.classList.add('loaded');
            }
            setTimeout(() => this.fitToContainer(), 100);
        }
    };
}

// Create viewer for sketch panel (top)
const sketchViewer = createSvgViewer('svg-container-sketch', 'svg-wrapper-sketch', 'header-sketch');

// Create viewer for profile panel (bottom) with overlay support
const profileViewer = {
    ...createSvgViewer('svg-container-profile', 'svg-wrapper-profile', 'header-profile'),

    // Override updateTransform to also update remover overlay
    updateTransform() {
        const profileWrapper = document.getElementById('svg-wrapper-profile');
        const removerWrapper = document.getElementById('svg-wrapper-remover');
        const transform = `translate(${this.translateX}px, ${this.translateY}px) scale(${this.scale})`;
        if (profileWrapper) profileWrapper.style.transform = transform;
        if (removerWrapper) removerWrapper.style.transform = transform;
    },

    setRemoverSVG(svgString) {
        const wrapper = document.getElementById('svg-wrapper-remover');
        const header = document.getElementById('header-remover');
        if (!wrapper) return;

        wrapper.innerHTML = svgString;
        const svg = wrapper.querySelector('svg');
        if (svg) {
            svg.style.width = 'auto';
            svg.style.height = 'auto';
        }
        if (header) {
            header.classList.add('loaded');
        }
        // Apply current transform to keep in sync
        this.updateTransform();
    }
};

// Initialize all viewers and toolbar buttons
function initSvgViewers() {
    sketchViewer.init();
    profileViewer.init();

    // Toolbar buttons affect both panels
    document.getElementById('zoom-in').addEventListener('click', () => {
        sketchViewer.scale *= 1.2; sketchViewer.updateTransform();
        profileViewer.scale *= 1.2; profileViewer.updateTransform();
    });
    document.getElementById('zoom-out').addEventListener('click', () => {
        sketchViewer.scale /= 1.2; sketchViewer.updateTransform();
        profileViewer.scale /= 1.2; profileViewer.updateTransform();
    });
    document.getElementById('zoom-reset').addEventListener('click', () => {
        sketchViewer.reset();
        profileViewer.reset();
    });
    document.getElementById('zoom-fit').addEventListener('click', () => {
        sketchViewer.fitToContainer();
        profileViewer.fitToContainer();
    });
}

