/**
 * Call server API to parse DXF file
 * @param {string} dxfText - The DXF file content as string
 * @returns {Promise<object>} - Parsed DXF data from server
 */
async function parseDxfViaApi(dxfText) {
    const response = await fetch('/api/parse-dxf', {
        method: 'POST',
        headers: { 'Content-Type': 'text/plain' },
        body: dxfText
    });

    if (!response.ok) {
        const err = await response.json();
        throw new Error(err.error || 'Failed to parse DXF');
    }

    return await response.json();
}

