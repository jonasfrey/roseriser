function initMonaco() {
    return new Promise((resolve) => {
        require.config({ paths: { vs: 'https://cdnjs.cloudflare.com/ajax/libs/monaco-editor/0.45.0/min/vs' } });
        require(['vs/editor/editor.main'], function () {
            state.editor = monaco.editor.create(document.getElementById('editor-container'), {
                value: '// Upload DXF files to generate SCAD output',
                language: 'cpp',
                theme: 'vs-dark',
                automaticLayout: true,
                readOnly: true,
                minimap: { enabled: false }
            });
            resolve();
        });
    });
}

// ============ FILE HANDLING ============

function readFileAsText(file) {
    return new Promise((resolve, reject) => {
        const reader = new FileReader();
        reader.onload = () => resolve(reader.result);
        reader.onerror = reject;
        reader.readAsText(file);
    });
}

async function handleFileUpload(type, file) {
    try {
        updateStatus(`Parsing ${file.name}...`);
        const text = await readFileAsText(file);
        state.files[type] = { name: file.name, text };
        state.sketches[type] = await convertDxfToSketch(text);

        updateStatus(`Loaded ${file.name}`);
        processAllFiles();
    } catch (err) {
        updateStatus(`Error loading ${file.name}: ${err.message}`);
        console.error(err);
    }
}

function processAllFiles() {
    // Generate SVG previews for each loaded sketch
    if (state.sketches.sketch) {
        const svg = generateSvgFromSketch(state.sketches.sketch);
        sketchViewer.setSVG(svg);
        state.outputs.svg = svg;
        document.getElementById('dl-svg').disabled = false;
    }
    if (state.sketches.profile) {
        profileViewer.setSVG(generateSvgFromSketch(state.sketches.profile));
    }
    if (state.sketches.remover) {
        profileViewer.setRemoverSVG(generateSvgFromSketch(state.sketches.remover));
    }

    // Generate 3D preview if sketch and profile are available
    if (state.sketches.sketch && state.sketches.profile) {
        threeViewer.clearMeshes();
        render3DFromSketches(state.sketches.sketch, state.sketches.profile, threeViewer.scale);
        threeViewer.fitCameraToScene();
        document.getElementById('dl-stl').disabled = false;
    }

    // Generate JSON from all loaded sketches
    const jsonData = {};
    if (state.sketches.sketch) jsonData.sketch = state.sketches.sketch;
    if (state.sketches.profile) jsonData.profile = state.sketches.profile;
    if (state.sketches.remover) jsonData.remover = state.sketches.remover;
    state.outputs.json = JSON.stringify(jsonData, null, 2);
    document.getElementById('dl-json').disabled = !state.sketches.sketch;

    // Generate SCAD if all three files are loaded
    if (state.sketches.sketch && state.sketches.profile && state.sketches.remover) {
        const sketchName = state.files.sketch.name.replace(/\.dxf$/i, '');
        const profileName = state.files.profile.name.replace(/\.dxf$/i, '');
        const removerName = state.files.remover.name.replace(/\.dxf$/i, '');

        state.outputs.scad = generateScadFromSketches(
            state.sketches.sketch, sketchName,
            state.sketches.profile, profileName,
            state.sketches.remover, removerName
        );
        document.getElementById('dl-scad').disabled = false;
        updateStatus('All files processed - SCAD generated');
    } else if (state.sketches.sketch && state.sketches.profile) {
        const profileName = state.files.profile.name.replace(/\.dxf$/i, '');
        state.outputs.scad = f_s_scad_profile_functions_from_o_sketch(state.sketches.profile, profileName, true);
        document.getElementById('dl-scad').disabled = false;
        updateStatus('Profile loaded - upload remover for full SCAD output');
    } else if (state.sketches.sketch) {
        state.outputs.scad = '// Upload profile and profile remover DXF files to generate full SCAD output';
        updateStatus('Sketch loaded - upload profile files');
    }

    updateEditor();
}

function updateEditor() {
    if (!state.editor) return;
    const content = state.currentTab === 'scad' ? state.outputs.scad : state.outputs.json;
    const language = state.currentTab === 'scad' ? 'cpp' : 'json';
    monaco.editor.setModelLanguage(state.editor.getModel(), language);
    state.editor.setValue(content || '// No content yet');
}

function updateStatus(msg) {
    document.getElementById('status').textContent = msg;
}

// ============ VIEW SWITCHING ============

function switchView(view) {
    state.currentView = view;
    const svgPanels = document.getElementById('svg-panels');
    const threejsContainer = document.getElementById('threejs-container');
    const svgToolbar = document.getElementById('svg-toolbar');
    const threejsToolbar = document.getElementById('threejs-toolbar');

    if (view === 'svg') {
        svgPanels.classList.remove('hidden');
        threejsContainer.classList.remove('active');
        svgToolbar.style.display = 'flex';
        threejsToolbar.style.display = 'none';
    } else {
        svgPanels.classList.add('hidden');
        threejsContainer.classList.add('active');
        svgToolbar.style.display = 'none';
        threejsToolbar.style.display = 'flex';
        threeViewer.onResize();
    }
}

// ============ DOWNLOADS ============

function downloadFile(content, filename, mimeType) {
    const blob = new Blob([content], { type: mimeType });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
}

// ============ FILE SELECTION HANDLING ============

async function handleSelectChange(type, selectEl, fileInputEl) {
    const value = selectEl.value;

    if (value === 'custom') {
        // Trigger file input
        fileInputEl.click();
        // Reset select to show current state
        selectEl.value = '';
        return;
    }

    if (value === '') {
        return;
    }

    // Load example file
    try {
        updateStatus(`Loading ${value}...`);
        const response = await fetch(value);
        if (!response.ok) {
            throw new Error(`Failed to load ${value}`);
        }
        const text = await response.text();
        const filename = value.split('/').pop();

        state.files[type] = { name: filename, text };
        state.sketches[type] = await convertDxfToSketch(text);

        selectEl.classList.add('loaded');
        updateStatus(`Loaded ${filename}`);
        processAllFiles();
    } catch (err) {
        updateStatus(`Error: ${err.message}`);
        console.error(err);
        selectEl.value = '';
    }
}

function handleCustomFileUpload(type, file, selectEl) {
    handleFileUpload(type, file).then(() => {
        // Update select to show it's loaded with custom file
        selectEl.value = '';
        selectEl.classList.add('loaded');
    });
}

