const threeViewer = {
    scene: null,
    camera: null,
    renderer: null,
    controls: null,
    meshes: [],
    wireframe: false,
    scale: 0.5,

    init() {
        const container = document.getElementById('threejs-container');
        const rect = container.getBoundingClientRect();

        // Scene
        this.scene = new THREE.Scene();
        this.scene.background = new THREE.Color(0x222222);

        // Camera
        this.camera = new THREE.PerspectiveCamera(45, rect.width / rect.height, 0.1, 10000);
        this.camera.position.set(100, 100, 100);

        // Renderer
        this.renderer = new THREE.WebGLRenderer({ antialias: true });
        this.renderer.setPixelRatio(window.devicePixelRatio);
        this.renderer.setSize(rect.width, rect.height);
        container.appendChild(this.renderer.domElement);

        // Controls
        this.controls = new OrbitControls(this.camera, this.renderer.domElement);
        this.controls.enableDamping = true;
        this.controls.dampingFactor = 0.05;

        // Lights
        const ambientLight = new THREE.AmbientLight(0x404040, 2);
        this.scene.add(ambientLight);

        const directionalLight = new THREE.DirectionalLight(0xffffff, 1);
        directionalLight.position.set(100, 100, 100);
        this.scene.add(directionalLight);

        const directionalLight2 = new THREE.DirectionalLight(0xffffff, 0.5);
        directionalLight2.position.set(-100, -100, -100);
        this.scene.add(directionalLight2);

        // Grid helper
        const gridHelper = new THREE.GridHelper(200, 20, 0x444444, 0x333333);
        gridHelper.rotation.x = Math.PI / 2;
        this.scene.add(gridHelper);

        // Axes helper
        const axesHelper = new THREE.AxesHelper(50);
        this.scene.add(axesHelper);

        // Animation loop
        const animate = () => {
            requestAnimationFrame(animate);
            this.controls.update();
            this.renderer.render(this.scene, this.camera);
        };
        animate();

        // Resize handler
        window.addEventListener('resize', () => this.onResize());

        // Toolbar buttons
        document.getElementById('reset-camera').addEventListener('click', () => this.resetCamera());
        document.getElementById('toggle-wireframe').addEventListener('click', () => this.toggleWireframe());
        document.getElementById('scale-slider').addEventListener('input', (e) => {
            this.scale = parseFloat(e.target.value);
            document.getElementById('scale-value').textContent = this.scale.toFixed(1);
            this.updateMeshes();
        });
    },

    onResize() {
        const container = document.getElementById('threejs-container');
        const rect = container.getBoundingClientRect();
        this.camera.aspect = rect.width / rect.height;
        this.camera.updateProjectionMatrix();
        this.renderer.setSize(rect.width, rect.height);
    },

    resetCamera() {
        this.camera.position.set(100, 100, 100);
        this.camera.lookAt(0, 0, 0);
        this.controls.reset();
    },

    toggleWireframe() {
        this.wireframe = !this.wireframe;
        this.meshes.forEach(mesh => {
            if (mesh.material) mesh.material.wireframe = this.wireframe;
        });
    },

    clearMeshes() {
        this.meshes.forEach(mesh => {
            this.scene.remove(mesh);
            if (mesh.geometry) mesh.geometry.dispose();
            if (mesh.material) mesh.material.dispose();
        });
        this.meshes = [];
    },

    updateMeshes() {
        if (!state.sketches.sketch || !state.sketches.profile) return;
        this.clearMeshes();
        render3DFromSketches(state.sketches.sketch, state.sketches.profile, this.scale);
    },

    fitCameraToScene() {
        if (this.meshes.length === 0) return;

        const box = new THREE.Box3();
        this.meshes.forEach(mesh => box.expandByObject(mesh));

        const center = box.getCenter(new THREE.Vector3());
        const size = box.getSize(new THREE.Vector3());
        const maxDim = Math.max(size.x, size.y, size.z);

        this.camera.position.set(
            center.x + maxDim,
            center.y + maxDim,
            center.z + maxDim
        );
        this.camera.lookAt(center);
        this.controls.target.copy(center);
    },

    exportSTL() {
        if (this.meshes.length === 0) {
            console.warn('No meshes to export');
            return null;
        }

        const group = new THREE.Group();
        this.meshes.forEach(mesh => {
            const clonedMesh = mesh.clone();
            group.add(clonedMesh);
        });

        const exporter = new STLExporter();
        return exporter.parse(group, { binary: false });
    },

    exportSTLBinary() {
        if (this.meshes.length === 0) {
            console.warn('No meshes to export');
            return null;
        }

        const group = new THREE.Group();
        this.meshes.forEach(mesh => {
            const clonedMesh = mesh.clone();
            group.add(clonedMesh);
        });

        const exporter = new STLExporter();
        return exporter.parse(group, { binary: true });
    }
};

